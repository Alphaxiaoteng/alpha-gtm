func generatedImageBytes(t *testing.T) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, 8, 8))
	for y := 0; y < 8; y++ {
		for x := 0; x < 8; x++ {
			img.Set(x, y, color.RGBA{R: uint8(x * 20), G: uint8(y * 20), B: 90, A: 255})
		}
	}
	var buffer bytes.Buffer
	if err := png.Encode(&buffer, img); err != nil {
		t.Fatal(err)
	}
	return buffer.Bytes()
}

func newGenerateTestServer(t *testing.T, cfg config.Config) (*Server, *httptest.Server) {
	t.Helper()
	pngBytes := generatedImageBytes(t)
	encoded := base64.StdEncoding.EncodeToString(pngBytes)
	provider := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") == "" {
			w.WriteHeader(http.StatusUnauthorized)
			return
		}
		fmt.Fprintf(w, `{"candidates":[{"content":{"parts":[{"inlineData":{"mimeType":"image/png","data":%q}}]}}]}`, encoded)
	}))
	t.Cleanup(provider.Close)
	if cfg.DataDir == "" {
		cfg.DataDir = t.TempDir()
	}
	cfg.UIPort = 0
	cfg.AIImageEnabled = true
	cfg.ImageAPIProvider = "zexapi"
	cfg.ImageAPIBaseURL = provider.URL
	cfg.ImageAPIKey = "sk-test-offline-handler"
	cfg.AIImageModel = "gemini-3.1-flash-image"
	server, err := NewServer(cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { server.Close() })
	return server, provider
}

func TestAIImageGenerateWritesAssetAndServesItBack(t *testing.T) {
	server, _ := newGenerateTestServer(t, config.Config{})
	recorder := callAIImageAPI(t, server, http.MethodPost, "/api/ai-image/generate", map[string]any{
		"prompt": "a ceramic cup on a linen cloth", "aspect_ratio": "4:3", "image_size": "2K",
	})
	if recorder.Code != http.StatusOK {
		t.Fatalf("status=%d body=%s", recorder.Code, recorder.Body.String())
	}
	t.Logf("POST /api/ai-image/generate -> %d %s", recorder.Code, recorder.Body.String())
	var response struct {
		OK    bool   `json:"ok"`
		Name  string `json:"name"`
		URL   string `json:"url"`
		Mime  string `json:"mime"`
		Bytes int    `json:"bytes"`
		Model string `json:"model"`
	}
	if err := json.Unmarshal(recorder.Body.Bytes(), &response); err != nil {
		t.Fatal(err)
	}
	pngBytes := generatedImageBytes(t)
	if !response.OK || response.Name == "" || response.Mime != "image/png" || response.Bytes != len(pngBytes) {
		t.Fatalf("unexpected response: %s", recorder.Body.String())
	}
	if response.URL != "/api/ai-image/assets/"+response.Name {
		t.Fatalf("unexpected asset url: %s", response.URL)
	}
	if strings.Contains(recorder.Body.String(), "sk-test-offline-handler") || strings.Contains(recorder.Body.String(), "http://127.0.0.1") {
		t.Fatalf("response leaks provider details: %s", recorder.Body.String())
	}

	fileRecorder := callAIImageAPI(t, server, http.MethodGet, response.URL, nil)
	if fileRecorder.Code != http.StatusOK {
		t.Fatalf("asset read status=%d", fileRecorder.Code)
	}
	if !bytes.Equal(fileRecorder.Body.Bytes(), pngBytes) {
		t.Fatalf("served asset does not match generated bytes")
	}
}

