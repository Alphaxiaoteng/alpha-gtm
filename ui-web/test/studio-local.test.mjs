import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';

test('studio keeps a simple local library and explicit clip safety boundaries', async () => {
  const source = await readFile(new URL('../src/components/StudioView.tsx', import.meta.url), 'utf8');
  const content = await readFile(new URL('../src/components/ContentView.tsx', import.meta.url), 'utf8');
  const api = await readFile(new URL('../src/api.ts', import.meta.url), 'utf8');
  for (const section of ['media', 'scripts', 'clip']) assert.match(source, new RegExp(`id: '${section}'`));
  assert.match(source, /data-testid={`studio-section-\$\{id\}`}/);
  assert.match(source, /useState<StudioSection>\('media'\)/);
  assert.match(source, /添加素材/);
  assert.match(source, /本地素材绝对路径/);
  assert.match(source, /shared: '未分类'/);
  assert.doesNotMatch(source, /\['all', 'video', 'graph_text', 'article', 'shared'\]/);
  assert.doesNotMatch(source, /disabled=\{!isVideo\}/);
  assert.doesNotMatch(source, /studio-handoff-agent|handoffPlanToAgent/);
  assert.match(source, /window\.confirm\('将把所选素材的元数据和脚本文本发送给固定豆包 API/);
  assert.equal(source.match(/固定豆包 API/g)?.length, 1, 'provider disclosure should appear only in the confirmation');
  assert.match(source, /生成剪辑建议/);
  assert.match(source, /生成剪辑文件/);
  assert.doesNotMatch(source, /ffmpeg/);
  assert.match(source, /<summary className="cursor-pointer">技术详情<\/summary>/);
  assert.match(source, /confirmDiscardScriptDraft/);
  assert.match(source, /有未保存的脚本修改/);
  assert.match(source, /openPathInFinder/);
  assert.match(source, /在 Finder 中查看/);
  assert.match(source, /studio-media-filter-\$\{value\}/);
  assert.match(source, /const userMediaPurposes = \['video', 'graph_text', 'article'\]/);
  assert.match(source, /studio-script-content-type/);
  assert.match(source, /视频脚本/);
  assert.match(source, /图文脚本/);
  assert.match(source, /文章脚本/);
  assert.doesNotMatch(source, /refreshInterval|setInterval/);
  assert.doesNotMatch(source, /RefreshCw|>刷新</);
  assert.doesNotMatch(source, /local\/llama|127\.0\.0\.1:11434/);
  assert.match(content, /content-library-media-select/);
  assert.match(content, /attachContentMediaFromLibrary/);
  assert.match(content, /导入和管理在独立素材库完成/);
  assert.doesNotMatch(content, /selectMediaFile/);
  assert.doesNotMatch(api, /attachContentMedia:\s*\(contentID: number, path: string\)/);
  assert.match(api, /JSON\.stringify\(\{ library_id: libraryID, role, position \}\)/);
});
