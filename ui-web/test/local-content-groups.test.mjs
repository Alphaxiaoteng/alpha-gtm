import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';

test('local content creates article, image-text, and video drafts locally', async () => {
  const source = await readFile(new URL('../src/components/LocalContentView.tsx', import.meta.url), 'utf8');
  const settings = await readFile(new URL('../src/components/SettingsView.tsx', import.meta.url), 'utf8');
  const api = await readFile(new URL('../src/api.ts', import.meta.url), 'utf8');

  assert.match(source, /data-testid="content-library-board"/);
  assert.match(source, /ContentCover/);
  assert.match(source, /data-testid="local-content-add"/);
  assert.match(source, /data-testid="local-content-cleanup-open"/);
  assert.match(source, /data-testid="local-content-cleanup-modal"/);
  assert.match(source, /data-testid=\{`local-content-cleanup-item-\$\{item\.id\}`\}/);
  assert.match(source, /api\.deleteContent/);
  assert.match(source, /window\.confirm/);
  assert.match(source, /有发布记录的内容会保留/);
  assert.match(source, /data-testid="local-content-add-modal"/);
  assert.match(source, /data-testid="local-content-type-picker"/);
  assert.match(source, /local-content-type-\$\{value\}/);
  assert.match(source, /value: 'article',\s+label: '文章'/);
  assert.match(source, /value: 'graph_text',\s+label: '图文'/);
  assert.match(source, /value: 'video',\s+label: '视频'/);
  assert.match(source, /data-testid="local-content-detail-modal"/);
  assert.match(source, /data-testid="local-content-detail-cover"/);
  assert.match(source, /<ContentCover content=\{detail\} domain=\{domain\} controls/);
  assert.match(source, /data-testid="local-content-detail-fields"/);
  assert.match(source, /data-testid="local-content-detail-title"/);
  assert.match(source, /data-testid=\{`local-content-publication-\$\{item\.id\}`\}/);
  assert.match(source, /data-testid="local-content-detail-publication"/);
  assert.match(source, /item\.publish_count > 0 \|\| item\.status === 'published'/);
  assert.match(source, /已发布/);
  assert.match(source, /未发布/);
  assert.match(source, /<dt[^>]*>标题<\/dt>/);
  assert.match(source, /className="aspect-square w-full"/);
  assert.match(source, /点击封面查看详情/);
  assert.doesNotMatch(source, /data-testid="local-content-directory"/);
  assert.match(source, /extractContentTags/);
  assert.match(source, /data-testid="local-content-recognized-tags"/);
  assert.match(source, /tags_json: JSON\.stringify\(recognizedTags\)/);
  assert.match(source, /正文和描述会原样保留/);
  assert.match(source, /local-content-image-files/);
  assert.match(source, /Promise\.all\(imageFiles\.map/);
  assert.match(source, /api\.uploadContentImage\(image, selectedType\)/);
  assert.match(source, /data-testid="local-content-upload-dropzone"/);
  assert.match(source, /role="button"/);
  assert.match(source, /tabIndex=\{0\}/);
  assert.match(source, /openExternalURL/);
  assert.match(source, /role="dialog"/);
  assert.match(source, /onDrop=/);
  assert.match(source, /clipboardData\.files/);
	assert.match(source, /data-testid="local-content-planned-at"/);
	assert.match(source, /今天 20:00/);
	assert.match(source, /明天 20:00/);
	assert.match(source, /ReactMarkdown/);
	assert.match(source, /data-testid="markdown-preview"/);
	assert.match(source, /点击发布时同步到支持平台的原生定时/);
  assert.doesNotMatch(source, /AI 辅助生成/);
  assert.match(settings, /settings-content-library/);
  assert.match(settings, /视频、封面和图文图片会复制到此目录/);
  assert.match(api, /image_dir: string/);
  assert.match(api, /uploadContentImage/);
  assert.match(api, /form\.append\('purpose', purpose\)/);
  assert.match(api, /cover_media_id/);
});
