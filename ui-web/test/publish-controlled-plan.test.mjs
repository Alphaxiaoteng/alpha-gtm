import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

const source = await readFile(new URL('../src/components/PublishView.tsx', import.meta.url), 'utf8');
const apiSource = await readFile(new URL('../src/api.ts', import.meta.url), 'utf8');
const authorizationSource = await readFile(new URL('../src/publishPlanAuthorization.ts', import.meta.url), 'utf8');

test('controlled platform UI requires a second explicit action after prepare before one real submit', () => {
  assert.match(source, /api\.createPublishPlan/);
  assert.match(authorizationSource, /api\.approvePublishPlan/);
  assert.match(authorizationSource, /api\.preparePublishPlan/);
  assert.match(authorizationSource, /api\.submitPublishPlan/);
  assert.match(authorizationSource, /approvePublishPlan\(plan\.id, plan\.snapshotHash, 'prepare'\)/);
  assert.match(authorizationSource, /approvePublishPlan\(plan\.id, plan\.snapshotHash, 'submit'\)/);
  assert.doesNotMatch(source, /prepareExecution\.status === 'awaiting_review'/);
  assert.match(source, /hasPreparedPublishTarget\(prepareExecution\)/);
  assert.match(source, /target\.status === 'awaiting_review'/);
  assert.match(source, /target\.step === 'ready_to_submit'/);
  assert.match(source, /target\.step === 'review_or_submit'/);
  assert.match(source, /if \(!readyForSubmit\)/);
  assert.match(source, /canRetryUnsubmitted/);
  assert.match(source, /!target\.submitAttempted/);
  assert.match(source, /重试未提交账号/);
  assert.match(source, /prepareFrozenPlan/);
  assert.match(source, /submitPreparedPlan/);
  assert.doesNotMatch(source, /submitFrozenPlan|liveSubmitConfirmed/);
  assert.match(source, /data-testid="publish-plan-prepare"/);
  assert.match(source, /data-testid="publish-plan-submit"/);
  assert.match(source, /data-testid=\{`publish-plan-verify-manager-\$\{target\.account_id\}-\$\{target\.platform_code\}`\}/);
  assert.match(source, /verifyPublishPlanManager/);
  assert.match(source, /不会再次发布/);
  assert.match(source, /预填并打开平台/);
  assert.match(source, /确认并提交一次/);
  assert.match(source, /manualTakeoverActive/);
  assert.match(source, /历史人工状态（仅兼容旧记录）/);
  assert.doesNotMatch(source, /创作页已打开，等待人工完成/);
  assert.doesNotMatch(source, /填入已选平台（不会发布）/);
	assert.match(source, /一键发布/);
  assert.match(source, /publish-content-title-required/);
  assert.match(source, /publish-content-body-required/);
  assert.match(source, /publish-content-media-required/);
  assert.doesNotMatch(source, /PUBLISH_BROWSER_CLOSE_FAILED/);
  assert.match(authorizationSource, /snapshotHash/);
	assert.match(source, /24 \* 60 \* 60 \* 1000/);
	assert.match(source, /concurrency: 1/);
	assert.match(source, /firstReleaseManifests/);
	assert.match(source, /publishCapabilityFor/);
	assert.match(source, /supportsPublishContentType/);
	assert.match(source, /publish-select-platform-group/);
	assert.match(source, /publish-family-video/);
	assert.match(source, /publish-family-graph-text/);
	assert.match(source, />图文</);
	assert.match(source, />文章</);
	assert.doesNotMatch(source, /四平台视频账号|两平台文章账号/);
	assert.match(source, /selectableFamilyAssets/);
  assert.doesNotMatch(source, /未接入受控填写/);
  assert.match(apiSource, /'\/api\/publish-plans'/);
  assert.match(apiSource, /`\/api\/publish-plans\/\$\{id\}\/submit`/);
  assert.match(apiSource, /action:\s*'prepare'\s*\|\s*'submit'/);
  assert.match(apiSource, /method: 'POST'/);
});
